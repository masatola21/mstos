export const getIndustryMessage = (industry?: string, type: 'problem' | 'benefit' = 'problem'): string => {
  if (industry && INDUSTRY_MESSAGES[industry]) {
    return INDUSTRY_MESSAGES[industry][type];
  }
  // あいまいマッチ
  if (industry) {
    const matchedKey = Object.keys(INDUSTRY_MESSAGES).find(k => industry.includes(k) || k.includes(industry));
    if (matchedKey) return INDUSTRY_MESSAGES[matchedKey][type];
  }
  if (type === 'problem') {
    return '日々の業務において、特定の人（または経営者様ご自身）に手作業や二重入力、火消し対応が集中し、本来の経営戦略に使える時間が奪われていませんか？';
  }
  return 'スプレッドシートやLINEの自動化から専用Webアプリまで、御社の成長フェーズに最もフィットする形で「本当に現場で動く仕組み」を直接構築できます。';
};

